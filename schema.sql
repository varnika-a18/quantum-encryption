Explicit Data Scheme for SQLite Engine 

CREATE TABLE IF NOT EXISTS USERS(USER_ID INT PRIMARY KEY AUTOINCREMENT, USERNAME TEXT UNIQUE NOT NULL,PASSWORD_HASH TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS QUANTUM_SESSIONS(SESSION_ID TEXT PRIMARY KEY,ALICE_IDENTITY TEXT NOT NULL,BOB_IDENTITY TEXT NOT NULL,CALCULATED_QBER REAL NOT NULL, IS_COMPROMISED INT NOT NULL);
CREATE TABLE IF NOT EXISTS DATA_PACKETS(PACKET_ID INT PRIMARY KEY AUTOINCREMENT,SESSION_ID TEXT NOT NULL,SENDER TEXT NOT NULL,PLAIN_TEXT TEXT NOT NULL, CIPHER_TEXT TEXT NOT NULL);
